func TestRunRefusesAnIncompleteCall(t *testing.T) {
	dir := t.TempDir()
	messages := writeFile(t, dir, "messages", "aaa\nfeat: one\n")
	empty := writeFile(t, dir, "empty", "")
	cases := []struct {
		name string
		args []string
		want string
	}{
		{name: "no messages file named", args: nil, want: "-messages is required"},
		{name: "messages file missing", args: []string{"-messages=" + filepath.Join(dir, "none")}, want: "open"},
		{name: "empty range", args: []string{"-messages=" + empty}, want: "no commit message read"},
		{name: "text file missing", args: []string{"-messages=" + messages, "-text=" + filepath.Join(dir, "none")}, want: "open"},
		{name: "an argument left over", args: []string{"-messages=" + messages, "extra"}, want: "unexpected argument"},
		{name: "an unknown flag", args: []string{"-range=a..b"}, want: "parse flags"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var out bytes.Buffer
			err := run(tc.args, &out)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("run(%v) = %v, want an error naming %q", tc.args, err, tc.want)
			}
			if out.Len() != 0 {
				t.Fatalf("a refused call wrote %q", out.String())
			}
		})
	}
}

func TestReadBoundedRefusesAnOversizedFile(t *testing.T) {
	dir := t.TempDir()
	atLimit := writeFile(t, dir, "at-limit", strings.Repeat("x", maxInputBytes))
	if _, err := readBounded(atLimit); err != nil {
		t.Fatalf("readBounded(%d bytes) = %v, want nil", maxInputBytes, err)
	}
	over := writeFile(t, dir, "over", strings.Repeat("x", maxInputBytes+1))
	if _, err := readBounded(over); err == nil || !strings.Contains(err.Error(), "larger than") {
		t.Fatalf("readBounded(%d bytes) = %v, want a size error", maxInputBytes+1, err)
	}
}
