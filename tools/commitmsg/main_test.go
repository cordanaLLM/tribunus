func TestRefusalNamesTheLinesThatCreditATool(t *testing.T) {
	cases := []struct {
		name string
		line string
		want string
	}{
		{name: "co-author trailer with a model", line: "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", want: "trailer Co-Authored-By"},
		{name: "lower case key", line: "co-authored-by: Codex <codex@openai.com>", want: "trailer co-authored-by"},
		{name: "only the address names the vendor", line: "Co-authored-by: A Helper <noreply@anthropic.com>", want: "trailer Co-authored-by"},
		{name: "a forge assistant", line: "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>", want: "trailer Co-authored-by"},
		{name: "indented trailer", line: "  Co-authored-by: Gemini <gemini@google.com>", want: "trailer Co-authored-by"},
		{name: "space before the colon", line: "Co-authored-by : aider (some model)", want: "trailer Co-authored-by"},
		{name: "assisted-by trailer", line: "Assisted-by: Cursor", want: "trailer Assisted-by"},
		{name: "generated-with trailer", line: "Generated-with: OpenCode 1.18", want: "trailer Generated-with"},
		{name: "sign-off of a tool", line: "Signed-off-by: Devin <devin@example.com>", want: "trailer Signed-off-by"},
		{name: "footer with a link", line: "🤖 Generated with [Claude Code](https://claude.com/claude-code)", want: "line credits"},
		{name: "footer in plain words", line: "Generated by ChatGPT", want: "line credits"},
		{name: "footer in a sentence", line: "This patch was written using Windsurf.", want: "line credits"},
		{name: "footer with more spaces", line: "created   via  Antigravity", want: "line credits"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := refusal(tc.line)
			if !strings.Contains(got, tc.want) || got == "" {
				t.Fatalf("refusal(%q) = %q, want a reason naming %q", tc.line, got, tc.want)
			}
		})
	}
}

// Every name of the list is tried on its own, so a name that is dropped from the list
// fails here. The list is repeated on purpose: the test must not read it from the code.
func TestRefusalKnowsEveryListedTool(t *testing.T) {
	names := []string{
		"aider", "anthropic", "antigravity", "chatgpt", "claude", "codeium", "codex", "copilot",
		"cursor", "deepseek", "devin", "gemini", "gpt", "grok", "llama", "mistral", "ollama",
		"openai", "opencode", "qwen", "tabnine", "windsurf",
	}
	for i := 0; i < len(names); i++ {
		name := names[i]
		lines := []string{
			"Co-authored-by: " + name + " <bot@example.com>",
			"Co-authored-by: " + strings.ToUpper(name) + "-5 <bot@example.com>",
			"Generated with " + name,
			name + "-reviewed-by: A Person <person@example.com>",
		}
		for j := 0; j < len(lines); j++ {
			if refusal(lines[j]) == "" {
				t.Errorf("refusal(%q) = none, want a reason", lines[j])
			}
		}
		stays := "Co-authored-by: x" + name + "x <person@example.com>"
		if got := refusal(stays); got != "" {
			t.Errorf("refusal(%q) = %q, want none: the name is part of a longer word", stays, got)
		}
	}
}

