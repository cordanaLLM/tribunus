func TestSplitReadsTheRecordsOfAGitLog(t *testing.T) {
	log := "aaa\nfeat: one\n\nBody\n\x00bbb\nfix: two\n\x00\nccc\nchore: three\n"
	records, err := split(log)
	if err != nil {
		t.Fatalf("split = %v, want nil", err)
	}
	want := []string{"aaa\nfeat: one\n\nBody\n", "bbb\nfix: two\n", "ccc\nchore: three\n"}
	if len(records) != len(want) {
		t.Fatalf("split = %q, want %q", records, want)
	}
	for i := 0; i < len(want); i++ {
		if records[i] != want[i] {
			t.Errorf("record %d = %q, want %q", i, records[i], want[i])
		}
	}
}

func TestSplitRefusesALogWithoutAMessage(t *testing.T) {
	logs := []string{"", "\n", "\x00", "\x00\n\x00 \n"}
	for i := 0; i < len(logs); i++ {
		if got, err := split(logs[i]); err == nil || !strings.Contains(err.Error(), "no commit message read") {
			t.Errorf("split(%q) = %q, %v, want the empty-range error", logs[i], got, err)
		}
	}
}

func TestSplitBoundsTheNumberOfMessages(t *testing.T) {
	atLimit := strings.Repeat("a\nb\x00", maxMessages)
	if records, err := split(atLimit); err != nil || len(records) != maxMessages {
		t.Fatalf("split(%d messages) = %d records, %v, want all of them", maxMessages, len(records), err)
	}
	if _, err := split(atLimit + "a\nb\x00"); err == nil || !strings.Contains(err.Error(), "more than") {
		t.Fatalf("split(%d messages) = %v, want a limit error", maxMessages+1, err)
	}
}

func writeFile(t *testing.T, dir string, name string, content string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatalf("WriteFile = %v", err)
	}
	return path
}

